#!/usr/bin/env python3
"""Import official uniform-profile fields only; verify exact rational error sums.
Usage: python scripts/import_params.py PATH_TO_V4_RESULTS
"""
import csv,sys,pathlib,io
from decimal import Decimal, ROUND_FLOOR
from fractions import Fraction

DISPLAY_COLUMNS = {'Delta0_display', 'Delta_d_display', 'radius_display'}
OPTIONAL_COLUMNS = {'low_field_exclusion_cells', 'low_field_expression_lower_exact',
                    'minimum_certified_extension_degree', 'minimum_profile_queries',
                    'minimum_profile_eta_exact', 'minimum_profile_qa_bits',
                    'minimum_profile_total_IOP_bits_lower'}

def compact_csv(rows):
 fields = [key for key in rows[0] if key not in DISPLAY_COLUMNS and
           not (key in OPTIONAL_COLUMNS and all(not row[key] for row in rows))]
 output = io.StringIO(newline='')
 writer = csv.DictWriter(output, fieldnames=fields, extrasaction='ignore', lineterminator='\r\n')
 writer.writeheader()
 for row in rows:
  row = row.copy()
  for key in fields:
   if key.endswith('_bits_lower') and row[key] and row[key] not in ('infinity', 'same_event_as_primal'):
    row[key] = str(Decimal(row[key]).quantize(Decimal('0.001'), rounding=ROUND_FLOOR))
  writer.writerow(row)
 return output.getvalue().encode()
root=pathlib.Path(__file__).resolve().parents[1]; source=pathlib.Path(sys.argv[1])
rows=[]
inputs={}
for name in ('goldilocks','m127'):
 data=(source/f'{name}-parameters.csv').read_bytes()
 r=list(csv.DictReader(data.decode().splitlines()))
 if len(r)!=72:
  raise ValueError(f'{name}: expected 72 rows, got {len(r)}')
 for row_number,x in enumerate(r, start=2):
  def require(condition, message):
   if not condition:
    raise ValueError(f'{name} row {row_number}: {message}')
  require(x['certificate_version']=='hfc-tight-total100-gold-m127-v4-dual-2026-11-10', 'invalid certificate version')
  require(x['target_bits']=='100' and x['selection_profile']=='uniform' and x['analysis_only']=='False', 'invalid selection profile')
  terms=[Fraction(x[k]) for k in ('qa_failure_upper_exact','hfc_failure_upper_exact','algebra_failure_upper_exact','query_failure_upper_exact')]
  require(sum(terms)==Fraction(x['total_IOP_failure_upper_exact'])<Fraction(1,2**100), 'invalid exact failure bound')
  require(int(x['extension_degree'])==(3 if name=='goldilocks' else 2), 'invalid extension degree')
  eta=Fraction(x['eta_exact']); field=x['base_field']; backend='Rs' if x['backend']=='RS' else 'Qa'
  fields=dict(base_field='BaseFieldKind::'+field, backend='BaseCodeKind::'+backend)
  for k,col in [('mu','mu'),('mu0','mu0'),('r','r'),('c','c'),('extension_degree','extension_degree'),('num_queries','queries'),('d0_lower','d0_lower'),('b0_lower','b0_lower'),('td_upper','td')]:fields[k]=str(int(x[col]))
  fields.update(eta_num=str(eta.numerator),eta_den=str(eta.denominator),certified='true')
  rows.append('    HyperFoldConfig { '+', '.join(k+': '+v for k,v in fields.items())+' },')
 inputs[name]=compact_csv(r)
for name,data in inputs.items():
 (root/'data'/f'{name}-parameters.csv').write_bytes(data)
(root/'src/certified_params.rs').write_text('// Generated by scripts/import_params.py from exact v4 official CSV. Do not hand-edit.\npub const CERTIFIED_CONFIGS: &[HyperFoldConfig] = &[\n'+'\n'.join(rows)+'\n];\n')
print('Imported and exact-error-checked',len(rows),'official rows')
