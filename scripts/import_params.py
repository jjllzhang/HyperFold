#!/usr/bin/env python3
"""Import official uniform-profile fields only; verify exact rational error sums.
Usage: python scripts/import_params.py PATH_TO_V3_RESULTS
"""
import csv,sys,pathlib,hashlib
from fractions import Fraction
root=pathlib.Path(__file__).resolve().parents[1]; source=pathlib.Path(sys.argv[1])
rows=[]; manifest=[]
for name in ('goldilocks','m127'):
 data=(source/f'{name}-parameters.csv').read_bytes();(root/'data'/f'{name}-parameters.csv').write_bytes(data)
 manifest.append(f'{hashlib.sha256(data).hexdigest()}  {name}-parameters.csv')
 r=list(csv.DictReader(data.decode().splitlines()));assert len(r)==72
 for x in r:
  assert x['certificate_version']=='hfc-tight-total100-gold-m127-v3-2026-11-05'
  assert x['target_bits']=='100' and x['selection_profile']=='uniform' and x['analysis_only']=='False'
  terms=[Fraction(x[k]) for k in ('qa_failure_upper_exact','hfc_failure_upper_exact','algebra_failure_upper_exact','query_failure_upper_exact')]
  assert sum(terms)==Fraction(x['total_IOP_failure_upper_exact'])<Fraction(1,2**100)
  assert int(x['extension_degree'])==(3 if name=='goldilocks' else 2)
  eta=Fraction(x['eta_exact']); field=x['base_field']; backend='Rs' if x['backend']=='RS' else 'Qa'
  fields=dict(base_field='BaseFieldKind::'+field, backend='BaseCodeKind::'+backend)
  for k,col in [('mu','mu'),('mu0','mu0'),('r','r'),('c','c'),('extension_degree','extension_degree'),('num_queries','queries'),('d0_lower','d0_lower'),('b0_lower','b0_lower'),('td_upper','td')]:fields[k]=str(int(x[col]))
  fields.update(eta_num=str(eta.numerator),eta_den=str(eta.denominator),certified='true')
  rows.append('    HyperFoldConfig { '+', '.join(k+': '+v for k,v in fields.items())+' },')
(root/'src/certified_params.rs').write_text('// Generated by scripts/import_params.py from exact v3 official CSV. Do not hand-edit.\npub const CERTIFIED_CONFIGS: &[HyperFoldConfig] = &[\n'+'\n'.join(rows)+'\n];\n')
(root/'data/SHA256SUMS').write_text('\n'.join(manifest)+'\n')
print('Imported and exact-error-checked',len(rows),'official rows')
